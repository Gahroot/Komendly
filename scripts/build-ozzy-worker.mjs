// Builds Ozzy's SDF raster worker into public/ozzy/ (Turbopack in Next 16.1 copies `new Worker(new URL(...))`
// targets as raw .ts, so the worker is prebuilt here). Re-run after changing src/components/ozzy/sdf/* or types:
//   node scripts/build-ozzy-worker.mjs
// src/components/ozzy/__tests__/sdf-worker.test.ts fails when the committed bundle is stale.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

export async function bundleOzzyWorker() {
  const r = await build({
    entryPoints: ["src/components/ozzy/sdf/worker.ts"],
    bundle: true, minify: true, format: "iife", target: "es2020", write: false, legalComments: "none",
  });
  const code = r.outputFiles[0].text;
  return { code, version: createHash("sha256").update(code).digest("hex").slice(0, 10) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { code, version } = await bundleOzzyWorker();
  writeFileSync("public/ozzy/sdf-worker.js", code);
  writeFileSync("src/components/ozzy/sdf/worker-version.ts", `// Generated by scripts/build-ozzy-worker.mjs. Do not edit.\nexport const SDF_WORKER_VERSION = "${version}";\n`);
  console.log(`public/ozzy/sdf-worker.js ${code.length} bytes, v=${version}`);
}
