export {};
// Connect our own domains (bought at a registrar) to Maildoso, or list their state.
//   set -a; . ../.env.local; set +a; npx tsx scripts/maildoso-domains.ts list
//   set -a; . ../.env.local; set +a; npx tsx scripts/maildoso-domains.ts add trykomendly.com usekomendly.com
// "add" = POST /v1/user/domains/external (provider maildoso, redirect to komendly.com), then prints each domain's
// Maildoso nameservers as JSON lines {domain, ns[]} for the registrar step (Hostinger: `hostinger domains portfolio
// update-nameservers`). NS must be set within 24h. Never prints the token.
const token = process.env.MAILDOSO_API_TOKEN;
if (!token) throw new Error("MAILDOSO_API_TOKEN is not set");
const BASE = "https://api.maildoso.com";
const H = { Authorization: `Bearer ${token}`, Accept: "application/json", "Content-Type": "application/json" };

async function call(method: string, path: string, body?: unknown): Promise<unknown> {
  const res = await fetch(`${BASE}${path}`, { method, headers: H, ...(body ? { body: JSON.stringify(body) } : {}) });
  const text = await res.text();
  if (!res.ok) throw new Error(`maildoso ${method} ${path} ${res.status}: ${text.slice(0, 400)}`);
  return text ? JSON.parse(text) : null;
}

type Dom = { id?: number; domain_name?: string; name?: string; status?: string; domain_status?: string; accounts_limit?: number; ns?: unknown; name_servers?: unknown; nameservers?: unknown; [k: string]: unknown };
const nameOf = (d: Dom): string => String(d.domain_name ?? d.name ?? "").toLowerCase();
function nsOf(d: Dom): string[] {
  for (const k of ["name_servers", "nameservers", "ns", "ns_records"]) {
    const v = d[k];
    if (Array.isArray(v)) return v.map((x) => (typeof x === "string" ? x : String((x as { value?: string; host?: string }).value ?? (x as { host?: string }).host ?? ""))).filter(Boolean);
  }
  return [];
}

const [cmd, ...args] = process.argv.slice(2);
const listed = async (): Promise<Dom[]> => {
  const r = (await call("GET", "/v1/user/domains")) as Dom[] | { items?: Dom[] };
  return Array.isArray(r) ? r : (r.items ?? []);
};
if (cmd === "add") {
  const domains = args.map((d) => d.trim().toLowerCase()).filter(Boolean);
  if (!domains.length) throw new Error("usage: add <domain...>");
  const r = await call("POST", "/v1/user/domains/external", { domains, providers: domains.map(() => "maildoso"), redirect_to: domains.map(() => "https://www.komendly.com") });
  console.log(JSON.stringify({ added: ((r as { results?: Array<{ name: string; result: string }> } | null)?.results ?? []).map((x) => `${x.name}:${x.result}`) }));
}
// "mailboxes <perDomain> [--only domain] [--dry]": create mailboxes on every ACTIVE domain up to <perDomain> each.
// Senders are the two real Komendly personas (same as the Gmail boxes): "Ozzy at Komendly" and "Nolan at Komendly".
// Passwords are generated by Maildoso (Kly imports them via accounts-lookup). Idempotent: existing addresses are skipped.
const OZZY = ["ozzy", "ozzy.k", "ozzyk", "hey.ozzy", "hi.ozzy", "ozzy.ads", "ozzy.studio", "ozzy.wizard", "ozzy.creates", "ozzy.draws", "ask.ozzy", "ozzy.team", "ozzy.hello", "ozzy.gifts", "ozzy.design", "ozzyw", "ozzy.w", "ozzy.art", "ozzy.helps", "ozzy.makes", "ozzy.here", "ozzy.notes", "ozzy.mail", "ozzy.desk", "ozzy.hq"];
const NOLAN = ["nolan", "nolan.g", "nolang", "nolan.grout", "ngrout", "n.grout", "nolan.k", "nolank", "hey.nolan", "hi.nolan", "nolan.ads", "nolan.studio", "nolan.team", "nolan.hello", "nolan.here", "nolan.notes", "nolan.mail", "nolan.desk", "nolan.hq", "nolan.creates", "nolan.helps", "nolan.makes", "nolan.gifts", "nolan.design", "nolan.art"];
if (cmd === "mailboxes") {
  const per = Math.min(50, Math.max(1, Number(args[0] ?? 50)));
  const only = args.includes("--only") ? args[args.indexOf("--only") + 1] : null;
  const dry = args.includes("--dry");
  const existing = new Set<string>();
  for (let offset = 0; ; offset += 500) {
    const r = (await call("GET", `/v1/user/accounts-lookup?limit=500&offset=${offset}&order_by=id`)) as { items: Array<{ email_account: string }>; meta: { total: number } };
    for (const a of r.items) existing.add(a.email_account.toLowerCase());
    if (!r.items.length || offset + r.items.length >= r.meta.total) break;
  }
  const doms = (await listed()).filter((d) => String(d.domain_status ?? d.status) === "ACTIVE" && (!only || nameOf(d) === only));
  const want: Array<Record<string, unknown>> = [];
  for (const d of doms) {
    const dn = nameOf(d);
    const locals = OZZY.flatMap((o, i) => [o, NOLAN[i]!]).slice(0, per);
    for (const local of locals) {
      const address = `${local}@${dn}`;
      if (existing.has(address)) continue;
      const ozzy = local.includes("ozzy");
      want.push({ email_account: address, first_name: ozzy ? "Ozzy" : "Nolan", last_name: "at Komendly", ...(ozzy ? { picture_url: "https://www.komendly.com/brand/ozzy-classic-happy.png" } : {}) });
    }
  }
  console.log(JSON.stringify({ domains: doms.map(nameOf), existing: existing.size, toCreate: want.length, dry }));
  if (!dry) {
    for (let i = 0; i < want.length; i += 50) {
      const r = await call("POST", "/v1/user/accounts", want.slice(i, i + 50));
      // Never log the response: it contains the new mailboxes' passwords.
      const res = ((r as { results?: Array<{ id?: number; result?: string; message?: string }> } | null)?.results ?? []);
      console.log(JSON.stringify({ batch: i / 50 + 1, sent: want.slice(i, i + 50).length, created: res.filter((x) => x.id).length, failed: res.filter((x) => !x.id).map((x) => x.message ?? x.result).slice(0, 3) }));
    }
  }
}

if (cmd === "add" || cmd === "list") {
  for (const d of await listed()) console.log(JSON.stringify({ domain: nameOf(d), id: d.id ?? null, status: d.domain_status ?? d.status ?? null, ns: nsOf(d), accountsLimit: d.accounts_limit ?? null, raw_ns: d.name_servers ?? null }));
}
